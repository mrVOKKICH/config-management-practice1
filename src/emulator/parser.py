"""Разбор введённой строки на команду и аргументы."""


def parse_line(line):
    """Разделить строку по пробелам на команду и аргументы.

    Args:
        line: строка, введённая пользователем.

    Returns:
        Кортеж (команда, список аргументов). Для пустой строки
        возвращается (None, []).
    """
    parts = line.split()
    if not parts:
        return None, []
    return parts[0], parts[1:]
